function buildComponentMd(
  spec: Rec,
  componentKey: string,
  processingStates: ProcessingStates | undefined,
  parentKey?: string,
): string[] {
  const props = (spec.props ?? {}) as Rec;
  const anatomy = (spec.anatomy ?? {}) as Rec;
  const dflt = (spec.default ?? {}) as Rec;
  const variants = (spec.variants ?? []) as Rec[];
  const subcomponents = (spec.subcomponents ?? {}) as Rec;
  const title = (spec.title as string) ?? componentKey;

  const lines: string[] = [];
  lines.push(`# ${title}`);
  lines.push('');
  lines.push(
    '> Generated by `specs transform component-md` — a deterministic projection of the component spec.',
    '> Every value is verbatim from the spec; regenerate rather than edit.',
    `> Canonical data: \`api.yaml\` · \`variants.yaml\`.${parentKey ? ` Subcomponent of \`${parentKey}\`.` : ''}`,
    '>',
    '> **How to read.** To resolve a configuration: start from Element styles (default), then apply every',
    '> variant delta whose configuration matches, in the order listed — later values win per property.',
    '> `unset` removes the default value. `← prop` marks a value bound to a prop;',
    '> `` if `prop` op → a : b `` marks a conditional value. Tokens render as `` `path` (type, raw value) ``.',
    '> Shadows render as `[inset] offset-x offset-y blur spread color`.',
  );

  section(lines, 'Overview', buildOverview(title, props, anatomy, dflt, variants, subcomponents, spec));
  section(lines, 'Props', buildProps(props, anatomy, dflt, variants, processingStates));
  section(lines, 'Bindings', buildBindings(anatomy, dflt, variants, props), true);
  section(lines, 'States', buildStates(props, processingStates), true);
  section(lines, 'Anatomy', buildAnatomy(anatomy, dflt, variants, props));
  section(lines, 'Layout', buildLayout(dflt, variants));
  section(lines, 'Element styles (default)', buildDefaultStyles(dflt));
  section(lines, 'Typography', buildTypography(anatomy, dflt, variants), true);
  section(lines, 'Color', buildColor(dflt, variants), true);
  section(lines, 'Variant deltas', buildVariantDeltas(dflt, variants), true);
  section(lines, 'Invalid combinations', buildInvalidCombinations(spec, props, variants), true);
  section(lines, 'Subcomponents', buildSubcomponents(subcomponents), true);
  section(lines, 'Examples', buildExamples(spec, props), true);
  section(lines, 'Provenance', buildProvenance(spec));

  return lines;
}

/** Append a `## title` section. When optional, omit the section entirely if body is empty. */
function section(lines: string[], title: string, body: string[], optional = false): void {
  if (optional && body.length === 0) return;
  lines.push('', `## ${title}`, '');
  if (body.length === 0) {
    lines.push('_None._');
  } else {
    lines.push(...body);
  }
}

