/** Flatten Sides-style objects (padding.top …) and effects groups one level; pass everything else through. */
function flattenStyles(styles: Rec): Array<[string, unknown]> {
  const out: Array<[string, unknown]> = [];
  for (const [prop, value] of Object.entries(styles)) {
    if (isSidesObject(value)) {
      for (const [side, sv] of Object.entries(value as Rec)) {
        out.push([`${prop}.${side}`, sv]);
      }
    } else if (
      prop === 'effects' &&
      typeof value === 'object' &&
      value !== null &&
      !Array.isArray(value) &&
      !isTokenRef(value)
    ) {
      for (const [kind, ev] of Object.entries(value as Rec)) {
        out.push([`${prop}.${kind}`, ev]);
      }
    } else {
      out.push([prop, value]);
    }
  }
  return out;
}

function isSidesObject(v: unknown): boolean {
  if (typeof v !== 'object' || v === null || Array.isArray(v)) return false;
  const keys = Object.keys(v as Rec);
  return keys.length > 0 && keys.every(k => ['top', 'end', 'bottom', 'start'].includes(k));
}

const COLOR_PROPS = new Set(['backgroundColor', 'textColor', 'strokes']);

function isColorValue(value: unknown, prop: string): boolean {
  if (isTokenRef(value)) return (value as Rec).$type === 'color';
  if (typeof value === 'string' && /^#[0-9a-fA-F]{3,8}$/.test(value)) return true;
  if (COLOR_PROPS.has(prop) && value !== undefined) return true;
  return false;
}

function formatValue(value: unknown): string {
  if (value === null) return 'unset';
  if (value === undefined) return '—';
  if (isTokenRef(value)) {
    const t = value as { $token: string; $type?: string; $extensions?: Rec };
    const raw = tokenRawValue(t);
    const qualifier = [t.$type, raw].filter(Boolean).join(', ');
    return `${code(t.$token)}${qualifier ? ` (${qualifier})` : ''}`;
  }
  if (Array.isArray(value)) {
    return value.map(v => formatValue(v)).join('; ');
  }
  if (typeof value === 'object') {
    const v = value as Rec;
    // JSON Pointer refs (e.g. instanceOf: { $ref: '#/subcomponents/x' }) render as the pointer basename.
    if (typeof v.$ref === 'string') {
      const segments = v.$ref.split('/');
      return code(segments[segments.length - 1]);
    }
    // Shadow-shaped objects render as a compact CSS-like string (offset-x offset-y blur spread color).
    if ('offsetX' in v || 'blur' in v) {
      const parts = [
        v.visible === false ? '(hidden)' : null,
        v.inset ? 'inset' : null,
        v.offsetX,
        v.offsetY,
        v.blur,
        v.spread,
        v.color,
      ]
        .filter(x => x !== null && x !== undefined)
        .map(String);
      return code(parts.join(' '));
    }
    const binding = extractBinding(value);
    if (binding) {
      if (!binding.condition) return `← ${code(binding.propName)}`;
      return `if ${binding.condition}${binding.outcome ? ` ${binding.outcome}` : ''}`;
    }
    // Inline typography objects render as `family style size/line-height`.
    if ('fontFamily' in v || 'fontSize' in v) {
      const size = [v.fontSize, v.lineHeight].filter(x => x !== undefined).join('/');
      const parts = [v.fontFamily, v.fontStyle, size].filter(x => x !== undefined && x !== '').map(String);
      return code(parts.join(' '));
    }
    return code(JSON.stringify(v));
  }
  return code(formatScalar(value));
}

/** Resolved raw value from $extensions["com.figma"].rawValue, when the token format carries it. */
function tokenRawValue(t: { $extensions?: Rec }): string | null {
  const raw = ((t.$extensions?.['com.figma'] as Rec | undefined) ?? {}).rawValue;
  if (raw === undefined || raw === null) return null;
  if (typeof raw === 'object') {
    const hex = (raw as Rec).hex;
    return typeof hex === 'string' ? hex : null;
  }
  return String(raw);
}

function formatScalar(value: unknown): string {
  if (value === null) return 'null';
  return String(value);
}

function formatConfiguration(configuration: Rec): string {
  const parts = Object.entries(configuration).map(([k, v]) => `${k}: ${v}`);
  return parts.length > 0 ? code(parts.join(', ')) : code('(default)');
}

