import fs from 'fs-extra';
import path from 'path';
import yaml from 'yaml';
import type { Transformer, TransformerContext } from '../Types/Transformer.js';
import { CONCEPT_TABLE, buildOmittedProps, type ProcessingStates } from './states.js';
import { isTokenRef } from './css/values.js';

type Rec = Record<string, unknown>;

/**
 * Emits `component.md` — a deterministic, single-file markdown reference for a
 * component, projected verbatim from the spec (api.yaml + variants.yaml).
 * No inference: every value is a mechanical restatement of spec data.
 */
export class ComponentMdTransformer implements Transformer {
  readonly name = 'component-md';

  async run(apiYaml: Rec, context: TransformerContext): Promise<void> {
    const { outputDir, componentKey } = context;

    const variantsYaml = await readSiblingYaml(outputDir, 'variants.yaml');
    const examplesYaml = await readSiblingYaml(outputDir, 'examples.yaml');

    const spec = mergeConcerns(apiYaml, variantsYaml, examplesYaml);
    const lines = buildComponentMd(spec, componentKey, context.processingStates);
    await fs.writeFile(path.join(outputDir, 'component.md'), lines.join('\n') + '\n', 'utf-8');

    // Subcomponents — each gets its own subfolder/component.md
    const apiSubs = (apiYaml.subcomponents ?? {}) as Rec;
    const variantSubs = ((variantsYaml?.subcomponents ?? {})) as Rec;
    for (const [subKey, subApiRaw] of Object.entries(apiSubs)) {
      const subApi = subApiRaw as Rec;
      const subVariants = (variantSubs[subKey] ?? {}) as Rec;
      const subSpec = mergeConcerns(subApi, subVariants, undefined);
      const subLines = buildComponentMd(subSpec, subKey, context.processingStates, componentKey);
      const subDir = path.join(outputDir, subKey);
      await fs.ensureDir(subDir);
      await fs.writeFile(path.join(subDir, 'component.md'), subLines.join('\n') + '\n', 'utf-8');
    }
  }
}

async function readSiblingYaml(dir: string, name: string): Promise<Rec | undefined> {
  const p = path.join(dir, name);
  if (!fs.existsSync(p)) return undefined;
  const raw = await fs.readFile(p, 'utf-8');
  return yaml.parse(raw) as Rec;
}

/** Combine api/variants/examples concerns into one spec-shaped record. api.yaml may already be monolithic. */
function mergeConcerns(api: Rec, variants: Rec | undefined, examples: Rec | undefined): Rec {
  return {
    ...api,
    default: variants?.default ?? api.default,
    variants: variants?.variants ?? api.variants ?? [],
    invalidVariantCombinations: variants?.invalidVariantCombinations ?? api.invalidVariantCombinations,
    slotContentExamples: examples?.slotContentExamples ?? api.slotContentExamples,
    instanceExamples: examples?.instanceExamples ?? api.instanceExamples,
  };
}

